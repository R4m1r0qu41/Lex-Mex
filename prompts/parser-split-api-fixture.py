#!/usr/bin/env python3
"""Generate the compile-only lex_parse public-API fixture from the baseline B.

Usage: python3 prompts/parser-split-api-fixture.py BASELINE_SHA > crates/lex-cli/tests/lex_parse_api_compat.rs

Every public path that existed in lex-parse at BASELINE_SHA is imported by name,
so the same file must compile against the baseline and against any candidate.
Read from git, never from the working tree, so the fixture cannot encode the
candidate's layout.
"""
import re
import subprocess
import sys

baseline = sys.argv[1]
files = subprocess.run(
    ["git", "ls-tree", "-r", "--name-only", baseline, "crates/lex-parse/src"],
    capture_output=True, text=True, check=True,
).stdout.split()
ITEM = re.compile(r"^pub (?:(?:async|const|unsafe) )*(fn|struct|enum|const|type|trait|static)\s+([A-Za-z_][A-Za-z_0-9]*)")
paths = set()
modules = set()
for f in files:
    stem = f.rsplit("/", 1)[1][:-3]
    text = subprocess.run(["git", "show", f"{baseline}:{f}"], capture_output=True, text=True, check=True).stdout
    prod = text.split("#[cfg(test)]\nmod tests")[0]
    for line in prod.split("\n"):
        m = ITEM.match(line)
        if m:
            paths.add(("lex_parse::" if stem == "lib" else f"lex_parse::{stem}::") + m.group(2))
    if stem == "lib":
        for m in re.finditer(r"^pub mod ([a-z_]+);", prod, re.M):
            modules.add(m.group(1))
        for m in re.finditer(r"^pub use ([a-z_]+)::\{([^}]*)\};|^pub use ([a-z_]+)::([A-Za-z_]+);", prod, re.M):
            if m.group(1):
                for name in re.split(r",\s*", m.group(2).replace("\n", " ")):
                    name = name.strip()
                    if name:
                        paths.add(f"lex_parse::{name}")
            else:
                paths.add(f"lex_parse::{m.group(4)}")
print("//! Compile-only check that every public lex-parse path of the baseline still")
print(f"//! resolves. Generated by prompts/parser-split-api-fixture.py from {baseline}.")
print("#![allow(unused_imports)]")
print()
for mod in sorted(modules):
    print(f"use lex_parse::{mod} as _;")
for path in sorted(paths):
    print(f"use {path} as _;")
print()
print("#[test]")
print("fn lex_parse_public_paths_resolve() {}")
